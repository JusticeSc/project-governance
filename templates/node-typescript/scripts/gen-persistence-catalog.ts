/** Generate the declared market-index schema without claiming runtime compatibility. */
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { extractPersistenceSchema } from './persistence-schema.ts'
import { persistenceSchemaSnapshot, type PersistenceSchemaInventory } from './persistence-schema-model.ts'
import { renderPersistencePair, type PersistenceArtifact } from './persistence-artifacts.ts'

/** Render the current source inventory and its bilingual structural catalog.
 * @param root - independent project checkout.
 * @param current - complete freshly extracted graph.
 * @returns generated artifacts; no source or history is changed.
 */
export function persistenceCatalogArtifacts(root: string, current: PersistenceSchemaInventory): PersistenceArtifact[] {
  const page = (zh: boolean): string => [
    `# ${zh ? '当前市场索引结构' : 'Current market-index structure'}`, '',
    zh ? '[English](README.md) | 中文' : 'English | [中文](README.zh.md)', '',
    zh ? '由 `scripts/gen-persistence-catalog.ts` 从实际 `MarketIndex` 类型及所有可达类型生成。' : 'Generated by `scripts/gen-persistence-catalog.ts` from the actual `MarketIndex` type and every reachable type.', '',
    zh ? '完整图见 [schema.json](schema.json)。摘要不证明验证器行为或读取兼容性；评审须比较 base/head 并检查实际读取器。' : 'The complete graph is in [schema.json](schema.json). Digests do not prove validator behavior or reader compatibility; review must compare base/head and inspect actual readers.', '',
    `## ${zh ? '根类型' : 'Roots'}`, '', '| Root | SHA-256 |', '|---|---|',
    ...current.roots.map(item => `| \`${item.key}\` | \`${item.digest}\` |`), '',
    `## ${zh ? '可达类型' : 'Reachable types'}`, '', '| SHA-256 | Source names |', '|---|---|',
    ...current.types.map(item => `| \`${item.digest}\` | ${item.names.map(name => `\`${name.replaceAll('|', '&#124;')}\``).join(', ')} |`), '',
  ].join('\n')
  return [
    { path: 'docs/persistence-changes/current/schema.json', content: JSON.stringify(persistenceSchemaSnapshot(current), null, 2) + '\n' },
    ...renderPersistencePair(root, 'docs/persistence-changes/current/README.md', page(false), page(true)),
  ]
}

/** Generate or check every current structural artifact.
 * @param args - optional --root and --check.
 * @returns an actionable completion message, or throws on stale artifacts.
 */
export function runPersistenceCatalog(args: readonly string[]): string {
  const { values } = parseArgs({ args: [...args], options: { root: { type: 'string' }, check: { type: 'boolean' } } })
  const root = resolve(values.root ?? resolve(import.meta.dirname, '..'))
  const artifacts = persistenceCatalogArtifacts(root, extractPersistenceSchema(root))
  for (const artifact of artifacts) {
    const path = resolve(root, artifact.path)
    const present = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    if (values.check === true) {
      if (present !== artifact.content) throw new Error(`${artifact.path}: missing or stale; run gen-persistence-catalog`)
    } else if (present !== artifact.content) {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, artifact.content)
    }
  }
  return `${values.check === true ? 'Verified' : 'Generated'} ${artifacts.length} persistence catalog artifacts.`
}

if (process.argv[1] !== undefined && existsSync(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(import.meta.filename)) {
  try { console.log(runPersistenceCatalog(process.argv.slice(2))) }
  catch (error: unknown) { console.error(error instanceof Error ? error.message : String(error)); process.exitCode = 1 }
}
